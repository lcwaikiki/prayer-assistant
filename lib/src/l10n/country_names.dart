/// Localized display name for a country as returned by the prayer API
/// (Turkish). Falls back to English, then to the original [apiName].
String localizedCountryName(String apiName, String languageCode) {
  final iso = _turkishCountryToIso[apiName.toUpperCase()];
  if (iso == null) {
    return apiName;
  }
  final names = _cldrCountryNames[languageCode] ?? _cldrCountryNames['en']!;
  return names[iso] ?? _cldrCountryNames['en']![iso] ?? apiName;
}
